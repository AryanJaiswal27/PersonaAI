@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun DreamJournalScreen(viewModel: PersonaViewModel, onBack: () -> Unit) {
    val context = LocalContext.current
    val dreamHistory by viewModel.dreamHistory.collectAsState()
    var dreamSearchQuery by remember { mutableStateOf("") }
    var dreamToDelete by remember { mutableStateOf<Pair<String, String>?>(null) }

    val filteredDreams = remember(dreamHistory, dreamSearchQuery) {
        if (dreamSearchQuery.isBlank()) dreamHistory else dreamHistory.filter { (timestamp, dream) ->
            timestamp.contains(dreamSearchQuery, ignoreCase = true) ||
            dream.contains(dreamSearchQuery, ignoreCase = true)
        }
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Dream Journal & Explorer", fontWeight = FontWeight.Bold) },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.Filled.ArrowBack, contentDescription = "Back")
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = Color(0xFF070B14),
                    titleContentColor = Color(0xFFE6EDF3),
                    navigationIconContentColor = Color(0xFFE6EDF3)
                )
            )
        },
        containerColor = Color(0xFF0D1117)
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
                .padding(horizontal = 16.dp)
        ) {
            Spacer(modifier = Modifier.height(16.dp))

            // Header Card
            Card(
                modifier = Modifier.fillMaxWidth(),
                colors = CardDefaults.cardColors(containerColor = Color(0xFF161B22)),
                shape = RoundedCornerShape(16.dp),
                border = androidx.compose.foundation.BorderStroke(1.dp, Color(0xFF30363D))
            ) {
                Column(modifier = Modifier.padding(16.dp)) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Icon(Icons.Filled.AutoAwesome, contentDescription = null, tint = Color(0xFFA855F7), modifier = Modifier.size(24.dp))
                        Spacer(modifier = Modifier.width(12.dp))
                        Text("Subconscious Architecture", style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold, color = Color(0xFFE6EDF3))
                    }
                    Spacer(modifier = Modifier.height(8.dp))
                    Text(
                        text = "Dreams are probabilistic futures generated by the AI based on your day's core memories, anxieties, and routines. They represent the internal emotional evolution of your digital twin.",
                        style = MaterialTheme.typography.bodySmall,
                        color = Color(0xFF8B949E)
                    )
                }
            }

            Spacer(modifier = Modifier.height(16.dp))

            // Search Bar
            OutlinedTextField(
                value = dreamSearchQuery,
                onValueChange = { dreamSearchQuery = it },
                placeholder = { Text("Search dreams by keywords or themes...") },
                leadingIcon = { Icon(Icons.Filled.Search, contentDescription = null, modifier = Modifier.size(18.dp)) },
                trailingIcon = {
                    if (dreamSearchQuery.isNotEmpty()) {
                        IconButton(onClick = { dreamSearchQuery = "" }) {
                            Icon(Icons.Filled.Clear, contentDescription = "Clear", modifier = Modifier.size(16.dp))
                        }
                    }
                },
                modifier = Modifier.fillMaxWidth(),
                singleLine = true,
                textStyle = MaterialTheme.typography.bodySmall,
                shape = RoundedCornerShape(12.dp)
            )

            Spacer(modifier = Modifier.height(16.dp))

            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    text = "Archived Dreams (${filteredDreams.size})",
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.SemiBold,
                    color = Color(0xFF58A6FF)
                )
            }
            Spacer(modifier = Modifier.height(10.dp))

            if (filteredDreams.isEmpty()) {
                Box(modifier = Modifier.fillMaxWidth().weight(1f), contentAlignment = Alignment.Center) {
                    Column(horizontalAlignment = Alignment.CenterHorizontally) {
                        Icon(Icons.Filled.Bedtime, contentDescription = null, modifier = Modifier.size(64.dp), tint = Color(0xFF30363D))
                        Spacer(modifier = Modifier.height(16.dp))
                        Text(
                            text = if (dreamSearchQuery.isNotEmpty()) "No dreams matching \"$dreamSearchQuery\"" else "No dreams recorded yet.",
                            color = Color(0xFF8B949E),
                            style = MaterialTheme.typography.bodyMedium
                        )
                        Text(
                            text = if (dreamSearchQuery.isNotEmpty()) "Try a different search keyword." else "Run Night Mode synthesis to generate a dream.",
                            color = Color(0xFF8B949E),
                            style = MaterialTheme.typography.bodySmall
                        )
                    }
                }
            } else {
                LazyColumn(
                    modifier = Modifier.fillMaxSize(),
                    verticalArrangement = Arrangement.spacedBy(16.dp)
                ) {
                    items(filteredDreams) { (timestamp, dream) ->
                        DreamCard(
                            timestamp = timestamp,
                            dream = dream,
                            onDelete = { dreamToDelete = timestamp to dream }
                        )
                    }
                    item { Spacer(modifier = Modifier.height(32.dp)) }
                }
            }
        }
    }

    if (dreamToDelete != null) {
        val (ts, content) = dreamToDelete!!
        AlertDialog(
            onDismissRequest = { dreamToDelete = null },
            title = {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Icon(Icons.Filled.Delete, contentDescription = null, tint = MaterialTheme.colorScheme.error)
                    Spacer(modifier = Modifier.width(8.dp))
                    Text("Delete Dream Entry", fontWeight = FontWeight.Bold)
                }
            },
            text = {
                Text("Are you sure you want to permanently delete this dream from $ts? This cannot be undone.")
            },
            confirmButton = {
                Button(
                    onClick = {
                        viewModel.deleteDream(ts, content)
                        dreamToDelete = null
                        Toast.makeText(context, "Dream deleted", Toast.LENGTH_SHORT).show()
                    },
                    colors = ButtonDefaults.buttonColors(containerColor = MaterialTheme.colorScheme.error)
                ) {
                    Text("Delete", maxLines = 1)
                }
            },
            dismissButton = {
                TextButton(onClick = { dreamToDelete = null }) {
                    Text("Cancel", maxLines = 1)
                }
            }
        )
    }
}

@Composable
fun DreamCard(timestamp: String, dream: String, onDelete: (() -> Unit)? = null) {
    Card(
        modifier = Modifier.fillMaxWidth(),
        colors = CardDefaults.cardColors(containerColor = Color(0xFF1C2128)),
        shape = RoundedCornerShape(12.dp),
        elevation = CardDefaults.cardElevation(defaultElevation = 4.dp)
    ) {
        Column(modifier = Modifier.padding(16.dp)) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Row(
                    modifier = Modifier.weight(1f).padding(end = 8.dp),
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Icon(Icons.Filled.Bedtime, contentDescription = null, tint = Color(0xFF58A6FF), modifier = Modifier.size(18.dp))
                    Spacer(modifier = Modifier.width(8.dp))
                    Text(
                        timestamp, 
                        style = MaterialTheme.typography.labelMedium, 
                        fontWeight = FontWeight.Bold, 
                        color = Color(0xFF58A6FF),
                        maxLines = 1,
                        overflow = androidx.compose.ui.text.style.TextOverflow.Ellipsis
                    )
                }

                Row(verticalAlignment = Alignment.CenterVertically) {
                    Surface(
                        shape = RoundedCornerShape(8.dp),
                        color = Color(0xFFA855F7).copy(alpha = 0.1f),
                        border = androidx.compose.foundation.BorderStroke(1.dp, Color(0xFFA855F7).copy(alpha = 0.3f))
                    ) {
                        Text(
                            text = "Synthesized",
                            style = MaterialTheme.typography.labelSmall,
                            modifier = Modifier.padding(horizontal = 8.dp, vertical = 2.dp),
                            color = Color(0xFFA855F7)
                        )
                    }

                    if (onDelete != null) {
                        Spacer(modifier = Modifier.width(6.dp))
                        IconButton(onClick = onDelete, modifier = Modifier.size(28.dp)) {
                            Icon(
                                Icons.Filled.Delete,
                                contentDescription = "Delete Dream",
                                tint = MaterialTheme.colorScheme.outline,
                                modifier = Modifier.size(16.dp)
                            )
                        }
                    }
                }
            }
            Spacer(modifier = Modifier.height(12.dp))
            Text(
                text = dream.take(5000),
                style = MaterialTheme.typography.bodyMedium,
                color = Color(0xFFE6EDF3),
                lineHeight = androidx.compose.ui.unit.TextUnit(20f, androidx.compose.ui.unit.TextUnitType.Sp)
            )
        }
    }
}
